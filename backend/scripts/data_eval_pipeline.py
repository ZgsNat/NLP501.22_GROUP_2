#!/usr/bin/env python3
"""Controlled evaluation-data pipeline.

Verifies the frozen benchmark, regenerates the canonical human-label report,
builds Djinni-QA Aggregate Human Gold, and writes an evidence registry. It
never renames pilot heuristics as production B3/P6/P7.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from app.eval import djinni, human, provenance  # noqa: E402

MANIFEST = ROOT / "data" / "eval" / "benchmark_v1.json"
CODING = ROOT / ".runtime" / "bench" / "coding"
SUMMARY = ROOT / "docs" / "DATA_EVAL_SUMMARY.md"


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def ensure_coding_bench() -> None:
    if (CODING / "gold.json").exists() and len(list((CODING / "cvs").glob("*.txt"))) >= 200:
        return
    CODING.mkdir(parents=True, exist_ok=True)
    git = lambda *a: subprocess.run(["git", *a], cwd=ROOT, check=True, capture_output=True).stdout  # noqa: E731
    files = git("ls-tree", "-r", "--name-only", "origin/coding", "data/synthetic", "data/jds/jds.yaml").decode().splitlines()
    for name in files:
        if name.endswith((".txt", "gold.json", "latent.json", "jds.yaml")):
            out = CODING / ("cvs/" + Path(name).name if name.endswith(".txt") else Path(name).name)
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_bytes(git("show", f"origin/coding:{name}"))


def verify_benchmark() -> tuple[bool, list[str]]:
    ensure_coding_bench()
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    failures = []
    for relative, expected in manifest["sha256"].items():
        path = ROOT / relative
        if not path.exists():
            failures.append(f"missing: {relative}")
        elif _sha(path) != expected:
            failures.append(f"hash mismatch: {relative}")
    return not failures, failures


def run_human_validation() -> str:
    return human.score()


def run_djinni_eval() -> dict:
    return djinni.run(write_report=True)


def run_circularity_audit() -> str:
    return provenance.write_report()


def render_summary(verified: bool, external: dict | None = None) -> str:
    gold = (external or {}).get("gold") or djinni.build_gold()
    stats = gold["agreement"]
    evaluated = (external or {}).get("evaluation", {})
    lines = [
        "# Controlled data-evaluation status", "",
        "Generated by `python backend/scripts/data_eval_pipeline.py --all`; measured and pending evidence are kept separate.", "",
        "## Frozen synthetic benchmark", "",
        f"- Manifest verification: **{'PASS' if verified else 'FAIL'}**.",
        "- The official split remains 10 test JDs. It was viewed before the lock, so it is not retroactively described as a virgin hold-out.",
        "- Hoa and Phúc independently graded the same 120-pair blind sample, including all 94 Claude A/B disagreements. See `docs/HUMAN_LABELS.md` for the registered decision.", "",
        "## Real-data external pilot", "",
        f"- Djinni-QA Aggregate Human Gold: **{len(gold['labels'])} pairs**, two human grades per pair, exact agreement **{stats['exact']:.1%}**, quadratic-weighted κ **{stats['weighted_kappa']:.3f}**.",
        f"- Confidence retained: {stats['confidence_counts']['high']} exact, {stats['confidence_counts']['medium']} one-grade gaps, {stats['confidence_counts']['low']} gaps of at least two.",
        "- Gold is the unrounded mean; P@5 relevance requires both annotators to grade at least 2. `min` and `max` are sensitivity bounds only.",
        "- Real CV/JD text stays in `.runtime/`; the committed artifact contains judgements and provenance only.", "",
        "## Evidence registry", "",
        "| Evidence | Status | May support | Must not be claimed as |",
        "|---|---|---|---|",
        "| 120-pair Hoa–Phúc sample | measured | human reliability of the internal silver set | human labels for all 600 pairs |",
        "| 424-pair Vũ–Đán Aggregate Gold | measured | human-labelled external validity on real Djinni text | adjudicated expert consensus |",
        "| Djinni keyword/BM25/criteria pilot | measured | reproducible pilot baselines | the official B0–B3/P6/P7 ladder |",
        "| B1/B2/production B3/P6/P7 on Djinni | pending controlled run | future external ladder | completed results |",
        "| Existing 10-JD test split | measured but previously viewed | historical official benchmark | uncontaminated new hold-out |",
        "| Claude rank on `ours-silver` (0.871→0.955) | **blocked** | historical diagnostic only | ranking-effectiveness evidence |",
        "| Claude S1 on `ours-silver` (0.942) | **blocked** | behaviour/cost failure analysis only | evidence that S1 ranks better |",
        "| LLM rank on `coding-rubric` (0.861→0.859) | diagnostic | evidence that the silver gain does not transfer | human-labelled validation |",
        "| LLM rank on Djinni-human | pending pre-registered run | future independent human evaluation | completed result |",
    ]
    if evaluated:
        lines += ["", "Pilot numbers are in `docs/EXTERNAL_VALIDITY.md`; no tuning decision may be made from them after this freeze."]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--all", action="store_true")
    parser.add_argument("--verify", action="store_true")
    parser.add_argument("--human", action="store_true")
    parser.add_argument("--djinni", action="store_true")
    parser.add_argument("--summary", action="store_true")
    parser.add_argument("--audit", action="store_true")
    args = parser.parse_args()
    if not any(vars(args).values()):
        args.all = True

    verified, failures = True, []
    external = None
    if args.all or args.verify:
        verified, failures = verify_benchmark()
        print(f"benchmark manifest: {'PASS' if verified else 'FAIL'}")
        for failure in failures:
            print(f"  {failure}")
    if args.all or args.human:
        run_human_validation()
        print("human report -> docs/HUMAN_LABELS.md")
    if args.all or args.djinni:
        external = run_djinni_eval()
        print("Djinni gold -> data/eval/human_djinni_gold.json")
        print("Djinni report -> docs/EXTERNAL_VALIDITY.md")
    if args.all or args.audit:
        run_circularity_audit()
        print("circularity audit -> docs/CIRCULARITY_AUDIT.md")
    if args.all or args.summary:
        SUMMARY.write_text(render_summary(verified, external), encoding="utf-8")
        print(f"summary -> {SUMMARY}")


if __name__ == "__main__":
    main()
