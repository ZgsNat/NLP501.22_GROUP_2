"""Error analysis: the mistakes that matter to HR, with a deterministic diagnosis of why each one happened.

    misses        a relevant CV (gold ≥ 2) ranked below 10 although every CV graded at least as high fits in the
                  top 10: an avoidable miss, HR never sees a good candidate
    false alarms  an irrelevant CV (gold 0) in the top 5: HR wastes an interview slot

    python -m app.eval.errors [systems …] [--bench coding] → docs/ERROR_ANALYSIS.md (default: B3 on Settings.jd_parser, P6)
"""

import argparse
import json
from collections import Counter

from app.agent.scoring import knockout_reason, rule_criteria
from app.config import ROOT, get_settings
from app.eval.bench import load
from app.eval.run import OUT, result_path
from app.nlp import quality
from app.nlp.pipeline import process

DOC = ROOT / "docs" / "ERROR_ANALYSIS.md"


def diagnose(p, req: dict, subs: dict, gold: float) -> str:
    """One cause, most specific first."""
    if "garbled_text" in quality.flags(p):
        return "garbled text: the parser cannot read the CV"
    ko = knockout_reason(p, req["must_have"], subs)
    if gold >= 2 and ko:
        return f"knocked out: {ko.split(';')[0][:70]}"
    crit = rule_criteria(p, req, subs)
    if gold >= 2:
        weak = sorted(crit, key=lambda k: crit[k]["score"])[:2]
        return "low rule scores on " + ", ".join(f"{k} {crit[k]['score']}" for k in weak)
    hedged = [m for m in req["must_have"] if (b := p.best(m)) and b.strength == "hedged"]
    if hedged:
        return f"hedged must-have {hedged} still ranked high"
    listed = [m for m in req["must_have"] if (b := p.best(m)) and b.strength == "listed"]
    if listed:
        return f"must-have only listed, never used: {listed}"
    strong = sorted(crit, key=lambda k: -crit[k]["score"])[:2]
    return "high rule scores on " + ", ".join(f"{k} {crit[k]['score']}" for k in strong) + " (gold disagrees)"


def analyse(system: str, bench: str, only: list[str] | None = None) -> list[str]:
    b = load(bench)
    path = result_path(system, bench)
    if not path.exists():
        return [f"## {system} on `{bench}`", "", f"No results at {path}.", ""]
    per_jd = json.loads(path.read_text())["jds"]
    docs = {d.id: d for d in b.cvs}
    rows, causes = [], Counter()
    for jd in sorted(j for j in per_jd if only is None or j in only):
        order = per_jd[jd] if isinstance(per_jd[jd], list) else per_jd[jd]["ranking"]
        r = json.loads((OUT / "requirements" / bench / get_settings().jd_parser / f"{jd}.json").read_text())
        g = b.gold[jd]
        for rank, cid in enumerate(order, 1):
            # avoidable only if every CV graded at least this high fits in the top 10 (no tie pushes it out)
            group = sum(v >= g.get(cid, 0) for v in g.values())
            kind = ("miss" if g.get(cid, 0) >= 2 and rank > 10 and group <= 10
                    else "false alarm" if g.get(cid, 0) == 0 and rank <= 5 else None)
            if not kind or cid not in docs:
                continue
            p = process(cid, docs[cid].text, docs[cid].meta.get("headline", ""))
            why = diagnose(p, r["req"], r["subs"], g[cid])
            causes[(kind, why.split(":")[0].split(" on ")[0])] += 1
            rows.append(f"| {jd} | {cid} | {kind} | {g[cid]:g} | {rank} | {why} |")
    n = len([j for j in per_jd if only is None or j in only])
    lines = [f"## {system} on `{bench}`", "", f"{sum(k == 'miss' for k, _ in causes.elements())} avoidable misses, "
             f"{sum(k == 'false alarm' for k, _ in causes.elements())} false alarms over {n} JDs.", "",
             "| Error | cause | count |", "|---|---|---|"]
    lines += [f"| {k} | {c} | {n} |" for (k, c), n in causes.most_common()]
    lines += ["", "| JD | CV | error | gold | rank | diagnosis |", "|---|---|---|---|---|---|", *rows, ""]
    return lines


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("systems", nargs="*", default=[f"B3 8-axis ⊕ CE [{get_settings().jd_parser}]", "P6"])
    ap.add_argument("--bench", default="ours", choices=["ours", "coding", "test"])
    a = ap.parse_args()
    if a.bench == "test":  # NLP501-bench v1 test split, both sources (docs/BENCHMARK.md)
        m = json.loads((ROOT / "data" / "eval" / "benchmark_v1.json").read_text())["splits"]["test"]
        lines = [ln for s in a.systems for b in ("ours", "coding") for ln in analyse(s, b, m[b])]
        DOC.write_text("\n".join(["# Error analysis on the NLP501-bench v1 test split (generated by `python -m app.eval.errors "
                                  "--bench test`; do not edit by hand)", "", "Misses = relevant CVs (gold ≥ 2) ranked below 10 although "
                                  "every CV graded at least as high fits in the top 10 (avoidable); false alarms = irrelevant CVs (gold 0) in the top 5.", ""] + lines) + "\n")
        raise SystemExit(print(DOC.read_text()[:2500]))
    head = ["# Error analysis (generated by `python -m app.eval.errors`; do not edit by hand)", "",
            "Misses = relevant CVs (gold ≥ 2) ranked below 10 although every CV graded at least as high fits in the top 10 (avoidable); false alarms = irrelevant CVs (gold 0) in the top 5. "
            "The diagnosis is computed from the parsed CV and the JD requirements, most specific cause first.", ""]
    DOC.write_text("\n".join(head + [ln for s in a.systems for ln in analyse(s, a.bench)]) + "\n")
    print(DOC.read_text()[:3000])
