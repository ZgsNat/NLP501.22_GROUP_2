"""NLP501-bench v2 = v1 unchanged + the Djinni real-data layer in the test split (docs/BENCHMARK.md §v2).

Why: v1's test split has 10 JDs, so its 95% CIs are wide (P6 0.758–0.913) and every CV is synthetic. v2 adds the 8
Djinni JDs (real anonymised CVs, 250 per JD, pooled labels, condensed metrics) to test only: nothing is tuned on them.
v1 stays frozen and is still reported on its own; v2 is a second, larger test set.

    python -m app.eval.benchmark_v2 freeze     write data/eval/benchmark_v2.json (once; a change = v3)
    python -m app.eval.benchmark_v2 verify     check every input, v1's included
    python -m app.eval.benchmark_v2 report     → docs/BENCHMARK_V2_RESULTS.md

Djinni labels are silver (two LLM annotators) until the team's human labels are adjudicated: that switch is v2.1,
and the report states which labels it used.
"""

import argparse
import json

from app.config import ROOT
from app.eval import djinni
from app.eval import metrics
from app.eval.bench import load
from app.eval.benchmark import DAN, MANIFEST, SYSTEMS, _sha, split_tables
from app.eval.run import result_path, score_system
from app.eval.benchmark import verify as verify_v1

MANIFEST_V2 = ROOT / "data" / "eval" / "benchmark_v2.json"
DOC = ROOT / "docs" / "BENCHMARK_V2_RESULTS.md"
SOURCES = ("ours", "coding", "djinni")
V2_SYSTEMS = {**{k: v for k, v in SYSTEMS.items() if k != DAN},
              "B3 8-axis ⊕ CE-ft [hybrid]": "the same, with the cross-encoder fine-tuned on dev JDs (E20)",
              "E-every": "P6 with the LLM on every eligible candidate and every top-5 pair (cost reference)"}
PAIRS = (("B3 8-axis ⊕ CE [hybrid]", "B3 rules ⊕ CE"), ("B3 8-axis ⊕ CE [hybrid]", "B2 hybrid"),
         ("B3 8-axis ⊕ CE-ft [hybrid]", "B3 8-axis ⊕ CE [hybrid]"), ("P6", "B4"), ("P6", "B3 8-axis ⊕ CE [hybrid]"))


def _inputs() -> list:
    files = sorted((djinni.DIR / "cvs").glob("*.txt")) + [djinni.DIR / "jds.yaml", djinni.DIR / "labeling" / "pool.json"]
    return files + djinni.silver_files()


def freeze() -> dict:
    if MANIFEST_V2.exists():
        raise SystemExit(f"{MANIFEST_V2} exists: v2 is frozen. A changed benchmark is a new version.")
    if len(djinni.silver_files()) < 2:
        raise SystemExit("v2 needs both Djinni silver annotators: run `python -m app.eval.djinni silver` twice first")
    v1 = json.loads(MANIFEST.read_text())
    splits = {s: {**v1["splits"][s], "djinni": [d.id for d in djinni.jds()] if s == "test" else []}
              for s in ("test", "dev")}
    m = {"version": "NLP501-bench v2", "extends": "NLP501-bench v1 (data/eval/benchmark_v1.json, unchanged)",
         "djinni_ref": djinni.REF, "splits": splits,
         "labels": {**v1["labels"], "djinni": "silver: mean of two LLM annotators (Opus 5.5, Sonnet 5.5), 0–3, "
                                               "pooled pairs only; human-adjudicated labels = v2.1"},
         "sha256": {p.relative_to(ROOT).as_posix(): _sha(p) for p in _inputs()}}
    MANIFEST_V2.write_text(json.dumps(m, indent=1, ensure_ascii=False))
    return m


def verify() -> list[str]:
    m = json.loads(MANIFEST_V2.read_text())
    bad = [p for p, h in m["sha256"].items() if not (ROOT / p).exists() or _sha(ROOT / p) != h]
    return verify_v1() + bad


def report() -> str:
    m = json.loads(MANIFEST_V2.read_text())
    bad = verify()
    lines = ["# NLP501-bench v2 results (generated by `python -m app.eval.benchmark_v2 report`; do not edit by hand)", "",
             f"v1 unchanged + 8 Djinni JDs (real anonymised CVs) in test. Manifest: data/eval/benchmark_v2.json "
             f"({'all inputs match' if not bad else f'⚠️ {len(bad)} inputs changed: ' + ', '.join(bad[:5])}). "
             f"Djinni labels in use: **{djinni.gold()[1]}**; metrics there are condensed (judged CVs only). Each JD "
             "ranks its source's pool; mean over JDs with a 95% bootstrap CI; paired one-sided bootstrap p for “first "
             "> second”. Đán core is not run on Djinni and is left out here (see the v1 report). LLM: Claude Sonnet "
             "5.5 / Haiku 5.5; PYTHONHASHSEED=0.", ""]
    lines += split_tables(m, V2_SYSTEMS, SOURCES, PAIRS)
    lines += human_section()
    DOC.write_text("\n".join(lines), encoding="utf-8")
    return str(DOC)


def human_section() -> list[str]:
    """v2.1 preview: Djinni scored with the human labels next to the silver ones. Do the systems keep their order?"""
    found = djinni.human_gold()
    if not found:
        return []
    human, source = found
    silver = djinni.gold()[1] if not djinni.gold()[1].startswith("human") else None
    b = load("djinni")
    rows = []
    for s in V2_SYSTEMS:
        path = result_path(s, "djinni")
        if not path.exists():
            continue
        per_jd = json.loads(path.read_text())["jds"]
        a, h = score_system(per_jd, b.gold, b.traps), score_system(per_jd, human, b.traps)
        rows.append((s, sum(a["ndcg@10"]) / len(a["ndcg@10"]), sum(h["ndcg@10"]) / len(h["ndcg@10"]),
                     sum(h["p@5"]) / len(h["p@5"]), h["ndcg@10"]))
    if not rows:
        return []
    order_s = [r[0] for r in sorted(rows, key=lambda r: -r[1])]
    order_h = [r[0] for r in sorted(rows, key=lambda r: -r[2])]
    tau = metrics.kendall_tau_b([order_s.index(r[0]) for r in rows], [order_h.index(r[0]) for r in rows])
    lines = ["## Djinni with human labels (v2.1 preview, not the frozen v2 number)", "",
             f"Human labels: **{source}**. Silver: {silver or 'n/a'}. Same rankings, same 8 JDs, condensed metrics; "
             f"only the labels differ. Kendall τ between the two orders of systems: **{tau:.2f}**.", "",
             "| System | nDCG@10 silver | nDCG@10 human [95% CI] | Δ | P@5 human |", "|---|---|---|---|---|"]
    for s, ns, nh, p5, per in sorted(rows, key=lambda r: -r[2]):
        lines.append(f"| {s} | {ns:.3f} | " + "{:.3f} [{:.3f}, {:.3f}]".format(*metrics.bootstrap_ci(per))
                     + f" | {nh - ns:+.3f} | {p5:.3f} |")
    return lines + [""]


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["freeze", "verify", "report"])
    a = ap.parse_args()
    if a.what == "freeze":
        print(json.dumps(freeze()["splits"], indent=1))
    elif a.what == "verify":
        print("\n".join(verify()) or "benchmark v2 intact")
    else:
        print(report())
