"""E26 · Goal suite: does P7 handle complex HR goals like a controlled agent? (Q19, Q20)

Each case in data/goal_suite/goals.yaml is an HR goal with the behaviour expected of a controlled agent: formalize the
goal quoting HR, define a concept for what no taxonomy holds, check feasibility and go back to HR before ranking when
the goal is infeasible or unclear, recommend only CVs that meet HR's must-haves, and declare a shortfall instead of
hiding it. The pool is data/cvs plus data/goal_suite/cvs (CV-101..106 mention AI at different levels), indexed in an
in-memory store so the demo index is never overwritten. A scripted HR answers clarifications with the case's `hr`.

    DATA_DIR=$(uv run python -m app.eval.goals materialize) uv run python -m app.eval.goals [--only ai_goal] [--repeat 3]
        → docs/GOAL_RESULTS.md (claude_code by default; LLM cache on, off with --repeat > 1 so the runs can differ)
"""

import argparse
import asyncio
import shutil
import sys
from pathlib import Path

import yaml

from app.config import ROOT, Settings, get_settings
from app.eval.agentic import Task, Trace, run
from app.nlp.pipeline import profile

SUITE = ROOT / "data" / "goal_suite"
CORPUS = get_settings().runtime_dir / "bench" / "goal_suite_corpus"
OUT = ROOT / "docs" / "GOAL_RESULTS.md"


def materialize() -> Path:
    """data/ + the goal-suite CVs, laid out like data/ (DATA_DIR=<this dir>)."""
    data = ROOT / "data"
    for sub in ("cvs", "jds", "policies"):
        shutil.copytree(data / sub, CORPUS / sub, dirs_exist_ok=True)
    shutil.copytree(SUITE / "cvs", CORPUS / "cvs", dirs_exist_ok=True)
    for f in ("criteria_profiles.yaml", "skills_taxonomy.yaml"):
        shutil.copy(data / f, CORPUS / f)
    return CORPUS


def cases() -> list[dict]:
    return yaml.safe_load((SUITE / "goals.yaml").read_text(encoding="utf-8"))


def _order(tr: Trace) -> list[str]:
    return [n for _, n, _ in tr.tools]


def checks(case: dict, tr: Trace) -> dict[str, bool | None]:
    """Expected behaviour → passed? (None = not applicable)."""
    e, v, order = case["expect"], tr.values, _order(tr)
    short = v.get("shortlist", [])
    spec = v.get("goal_spec") or {}
    want = spec.get("count") or e.get("max_shortlist")
    limits = ((v.get("report") or {}).get("goal") or {}).get("limits") or []
    first = lambda a, b: a in order and (b not in order or order.index(a) < order.index(b))  # noqa: E731
    out = {
        "formalized the goal": "formalize_goal" in order if e.get("formalized") else None,
        "defined a concept": "define_concept" in order if e.get("concept") else None,
        "asked HR before ranking": (first("ask_hr", "screen") if e.get("asked_hr_before_screen")
                                    else None if "asked_hr_before_screen" not in e else "ask_hr" not in order),
        "recommended only CVs with HR's must-haves": all(
            all(k in profile(c).skills for k in e["musts"]) for c in short) if e.get("musts") and short else None,
        "shortlist within HR's count": len(short) <= e["max_shortlist"] if "max_shortlist" in e else None,
        "declared the shortfall": (bool(limits) if want and len(short) < want else None)
                                  if e.get("limits_iff_shortfall") else None,
        "within budget": not v.get("loops", {}).get("budget_stops"),
    }
    return out


def pass_rates(rows: list[tuple[dict, Trace, dict]]) -> dict[str, dict[str, tuple[int, int]]]:
    """case → check → (passed, runs where it applied), over repeated runs of the same case."""
    out: dict[str, dict[str, tuple[int, int]]] = {}
    for case, _, res in rows:
        for name, ok in res.items():
            if ok is not None:
                p, n = out.setdefault(case["id"], {}).get(name, (0, 0))
                out[case["id"]][name] = (p + bool(ok), n + 1)
    return out


def render(rows: list[tuple[dict, Trace, dict]], model: str) -> str:
    lines = ["# E26 · Goal suite (generated by `python -m app.eval.goals`; do not edit by hand)", "",
             f"Model: `{model}`. Pool: data/cvs + data/goal_suite/cvs (56 CVs). Scripted HR. Q19/Q20 in "
             "docs/AI_OUTPUT_CRITERIA.md; protocol in the module docstring.", "",
             "| case | checks passed | shortlist | goal check (code) | limits declared | tools | refusals | tokens |",
             "|---|---|---|---|---|---|---|---|"]
    total = passed = 0
    for case, tr, res in rows:
        got = [x for x in res.values() if x is not None]
        total, passed = total + len(got), passed + sum(got)
        goal = ((tr.values.get("report") or {}).get("goal") or {})
        lines.append(f"| {case['id']} | {sum(got)}/{len(got)} | {', '.join(tr.values.get('shortlist', [])) or '—'} | "
                     f"{'; '.join(goal.get('unmet', [])) or 'met'} | {len(goal.get('limits', []))} | "
                     f"{' → '.join(dict.fromkeys(_order(tr)))} | {len(tr.refused)} | "
                     f"{tr.usage.get('total_tokens', 0):,} |")
    lines += ["", f"**{passed}/{total} behaviour checks passed.**", ""]
    rates = pass_rates(rows)
    if any(n > 1 for checks_ in rates.values() for _, n in checks_.values()):
        lines += ["## Pass rate per check over repeated runs (LLM cache off)", "", "| case | check | passed |", "|---|---|---|"]
        lines += [f"| {cid} | {name} | {p}/{n} |" for cid, checks_ in rates.items() for name, (p, n) in checks_.items()]
        lines.append("")
    for case, tr, res in rows:
        lines += [f"## {case['id']}", "", f"Goal: “{case['goal']}”", ""]
        lines += [f"- {'✅' if ok else '❌'} {name}" for name, ok in res.items() if ok is not None]
        lines += [f"- refused: {r}" for r in tr.refused[:6]]
        lines += ["", "Answer to HR:", "", "> " + (tr.replies[-1] if tr.replies else "—").replace("\n", "\n> "), ""]
    return "\n".join(lines) + "\n"


async def main(only: set[str] | None, repeat: int = 1) -> None:
    from app.agent import nodes, tools
    from app.providers import cache
    from app.rag.corpus import load_dir
    from app.rag.retrieve import CHUNKS, WHOLE, chunk_items
    from app.rag.store import KnowledgeStore

    s = get_settings()
    if s.data_dir.resolve() != CORPUS.resolve():
        raise SystemExit("run with DATA_DIR=$(uv run python -m app.eval.goals materialize)")
    store = KnowledgeStore(Settings(qdrant_url=":memory:", embed_dense_model=s.embed_dense_model))
    cvs = list(load_dir("cvs"))
    store.index(WHOLE, cvs)
    store.index_items(CHUNKS, chunk_items([profile(d.id) for d in cvs]))
    store.index("policies", list(load_dir("policies")))
    nodes.get_store = tools.get_store = lambda: store  # the demo's Qdrant index stays untouched
    if repeat == 1:  # repeated runs must reach the model each time, or they only replay the first
        cache.enable(s.runtime_dir / "llm_cache.sqlite")
    jds = {d.id: d for d in load_dir("jds")}
    rows = []
    for case in cases():
        if only and case["id"] not in only:
            continue
        for i in range(repeat):
            task = Task(case["id"], [case["jd"]], [], {}, goal=case["goal"])
            tr = await run(task, jds[case["jd"]], None, clarify=case["hr"])
            rows.append((case, tr, checks(case, tr)))
            print(f"{case['id']} run {i + 1}/{repeat}: {sum(x for x in rows[-1][2].values() if x)}/"
                  f"{sum(x is not None for x in rows[-1][2].values())} checks", flush=True)
    from app.providers.llm import default_spec
    OUT.write_text(render(rows, default_spec("reasoning")), encoding="utf-8")
    print(OUT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    if sys.argv[1:2] == ["materialize"]:
        print(materialize())
    else:
        ap = argparse.ArgumentParser()
        ap.add_argument("--only", default="")
        ap.add_argument("--repeat", type=int, default=1, help="runs per case (LLM cache off when > 1)")
        a = ap.parse_args()
        asyncio.run(main(set(filter(None, a.only.split(","))), max(1, a.repeat)))
