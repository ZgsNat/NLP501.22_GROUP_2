"""Fail-closed evidence provenance for ranking claims.

An LLM system may be *run* on labels made by an LLM, but that result is only a
diagnostic.  It cannot support an effectiveness claim when the judge is from
the same model family.  Human-labelled datasets are kept separate rather than
silently averaged with synthetic or model-labelled benchmarks.

    python -m app.eval.provenance  -> docs/CIRCULARITY_AUDIT.md
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from app.config import ROOT


@dataclass(frozen=True)
class LabelSource:
    key: str
    display: str
    kind: str
    family: str | None
    coverage: str


SOURCES = {
    "ours_silver": LabelSource(
        "ours_silver", "ours-silver", "llm", "claude", "600 pairs / 12 synthetic JDs"
    ),
    "coding_rubric": LabelSource(
        "coding_rubric", "coding-rubric", "rule_rubric", None, "synthetic rubric labels / 6 JDs"
    ),
    "human_internal": LabelSource(
        "human_internal", "Hoa–Phúc human audit", "human", None,
        "120 targeted pairs; not a complete ranking pool",
    ),
    "djinni_human": LabelSource(
        "djinni_human", "Djinni Aggregate Human Gold", "human", None,
        "424 judged pairs / 8 real JDs",
    ),
}


def claim_status(label_source: str, system_family: str | None = None) -> tuple[str, str]:
    """Return (status, reason); only human complete-pool evidence can be primary.

    ``blocked`` means the metric must not be used to claim ranking quality.
    ``diagnostic`` permits mechanism/error analysis, never a headline result.
    """
    source = SOURCES[label_source]
    family = (system_family or "").lower() or None
    if source.kind == "llm" and family == source.family:
        return "blocked", "same-family model-as-system/model-as-judge circularity"
    if source.kind == "llm":
        return "diagnostic", "model-created labels are secondary under the registered human-audit rule"
    if source.key == "human_internal":
        return "diagnostic", "human labels cover a targeted pair sample, not complete per-JD ranking pools"
    if source.kind == "rule_rubric":
        return "diagnostic", "non-LLM labels, but synthetic and generated from a scoring rubric"
    return "primary", "independent human relevance judgements on the frozen real-data pool"


def require_primary(label_source: str, system_family: str | None = None) -> None:
    status, reason = claim_status(label_source, system_family)
    if status != "primary":
        raise ValueError(f"{label_source} is {status}, not primary evidence: {reason}")


def render() -> str:
    rows = []
    for key, source in SOURCES.items():
        status, reason = claim_status(key, "claude")
        rows.append(
            f"| {source.display} | {source.kind} | {source.coverage} | **{status}** | {reason} |"
        )
    return "\n".join([
        "# Circularity audit and evidence firewall",
        "",
        "Generated by `python -m app.eval.provenance`; do not edit the decision table by hand.",
        "",
        "## Decision",
        "",
        "The historical Claude `rank_shortlist` result **0.871 → 0.955 and S1 result 0.942 are withdrawn from "
        "effectiveness claims**. The systems and the two silver judges are from the Claude family, while the "
        "rank-shortlist gain is absent on the separate rubric set (0.861 → 0.859). They remain diagnostic "
        "observations only. Claude annotators C and D are model annotations and never count as human evidence.",
        "",
        "`rank_shortlist` is disabled by default (`MAX_LLM_RANKS=0`). It may be enabled for an explicitly labelled "
        "experiment, but cannot become a default or a headline result until a frozen run is scored on Djinni "
        "Aggregate Human Gold (or another complete independent human-labelled pool).",
        "",
        "## Evidence classes for a Claude ranking system",
        "",
        "| label source | labels | coverage | claim status | reason |",
        "|---|---|---|---|---|",
        *rows,
        "",
        "## Separation rules",
        "",
        "1. Reports name columns `ours-silver`, `coding-rubric`, and `Djinni-human`; the ambiguous `ours` label is "
        "not used for a human result.",
        "2. Same-family LLM-as-judge metrics may be logged only as `blocked` diagnostics.",
        "3. The 120 Hoa–Phúc labels validate label reliability, but targeted sampling cannot produce an official "
        "full-pool nDCG score.",
        "4. Only the frozen 424-pair Djinni Aggregate Human Gold can currently support an external human-labelled "
        "ranking claim; unjudged pairs are ignored rather than treated as zero.",
        "5. Every future LLM-rank artifact must persist the exact candidate order and label provenance so it can be "
        "rescored without another model call.",
        "",
        "## Pre-registered release gate",
        "",
        "Unfreeze `rank_shortlist` only if a no-tuning Djinni run records all eight per-JD orders and the Aggregate "
        "Human Gold comparison is non-inferior to its deterministic base (mean ΔnDCG@10 ≥ −0.01), with the point "
        "estimate, JD bootstrap interval, conservative P@5, and lower/upper label-sensitivity bounds reported. "
        "A positive claim additionally requires the paired 95% bootstrap interval for ΔnDCG@10 to exclude zero.",
        "",
    ])


def write_report(path: Path | None = None) -> str:
    text = render()
    (path or ROOT / "docs" / "CIRCULARITY_AUDIT.md").write_text(text, encoding="utf-8")
    return text


if __name__ == "__main__":
    print(write_report())
