"""NLP501-bench v1.1: v1's rankings re-scored with the blind human labels where people graded (E27).

v1 stays frozen (its silver labels and its report do not change). v1.1 asks one question: does the order of the
systems hold when the 120 pairs two teammates graded blind replace the silver grade? Those 120 pairs are every pair
where the two silver annotators disagreed (94) plus 26 controls, on the 12 JDs of `ours`; the `coding` JDs keep their
rubric labels. The two people are merged with the rule used for Djinni (`djinni.adjudicate`: equal → kept, one apart
→ the lower grade, two or more apart → a conflict, reported and left at silver). No system is re-run: the stored
rankings of every system are scored again, so nothing here calls an LLM.

    python -m app.eval.benchmark_v1_1     → docs/BENCHMARK_V1_1_RESULTS.md
"""

import json
from copy import deepcopy

from app.config import ROOT
from app.eval import metrics
from app.eval.bench import load
from app.eval.benchmark import HEAD_TO_HEAD, MANIFEST, SYSTEMS
from app.eval.djinni import adjudicate
from app.eval.run import result_path, score_system

LABELS = ROOT / "data" / "eval"
HUMANS = ("human_hoa.json", "human_phuc.json")
DOC = ROOT / "docs" / "BENCHMARK_V1_1_RESULTS.md"


def human_grades() -> tuple[dict[tuple[str, str], int], list[tuple[str, str]]]:
    """→ (adjudicated human grade per (JD, CV), pairs left at silver because the two people were ≥ 2 apart)."""
    a, b = ({(x["jd"], x["cv"]): int(x["grade"]) for x in json.loads((LABELS / f).read_text(encoding="utf-8"))["labels"]}
            for f in HUMANS)
    return adjudicate(a, b)


def with_humans(gold: dict[str, dict[str, float]], human: dict[tuple[str, str], int]) -> dict[str, dict[str, float]]:
    """A copy of the silver gold with each human-graded pair replaced; pairs outside the gold are ignored."""
    out = deepcopy(gold)
    for (jd, cv), g in human.items():
        if jd in out and cv in out[jd]:
            out[jd][cv] = float(g)
    return out


def per_jd(system: str, golds: dict[str, dict]) -> dict[str, float]:
    """JD → nDCG@10 of a system's stored rankings, each source scored with the gold given for it."""
    out = {}
    for bench, g in golds.items():
        path = result_path(system, bench)
        if path.exists():
            sc = score_system(json.loads(path.read_text(encoding="utf-8"))["jds"], g, load(bench).traps)
            out.update(dict(zip(sc["jds"], sc["ndcg@10"])))
    return out


def order_tau(a: dict[str, float], b: dict[str, float]) -> float:
    """Kendall τ-b between two orderings of the same systems (by mean nDCG)."""
    names = sorted(set(a) & set(b))
    ra = {s: i for i, s in enumerate(sorted(names, key=lambda s: -a[s]))}
    rb = {s: i for i, s in enumerate(sorted(names, key=lambda s: -b[s]))}
    return metrics.kendall_tau_b([ra[s] for s in names], [rb[s] for s in names])


def report() -> str:
    m = json.loads(MANIFEST.read_text(encoding="utf-8"))
    human, conflicts = human_grades()
    ours, coding = load("ours"), load("coding")
    v1 = {"ours": ours.gold, "coding": coding.gold}
    v11 = {"ours": with_humans(ours.gold, human), "coding": coding.gold}
    changed = sum(1 for (jd, cv), g in human.items() if jd in ours.gold and cv in ours.gold[jd] and ours.gold[jd][cv] != g)
    lines = ["# NLP501-bench v1.1: v1 re-scored with blind human labels (generated by `python -m app.eval.benchmark_v1_1`;"
             " do not edit by hand)", "",
             f"Human labels: Hoa and Phúc, blind, {len(human) + len(conflicts)} pairs of `ours` (every pair the two silver "
             f"annotators disagreed on, plus controls), merged with the Djinni rule (equal → kept, one apart → lower). "
             f"{len(human)} pairs used, {len(conflicts)} left at silver (people ≥ 2 apart); the human grade differs from the silver mean on "
             f"{changed} of them (the silver grade is a mean of two models, often a half grade). `coding` keeps its "
             "rubric labels. Both columns score the same stored rankings, the ones in `.runtime/eval/results*` today: "
             "systems re-run after the v4.1 fixes differ from the frozen v1 report (BENCHMARK_RESULTS.md, 31 Oct), "
             "so the v1 column here is v1's labels on today's rankings. v1 itself is unchanged.", ""]
    for split in ("test", "dev"):
        jds = [j for src in ("ours", "coding") for j in m["splits"][split].get(src, [])]
        mean1, mean11, rows = {}, {}, {}
        for s in SYSTEMS:
            a, b = per_jd(s, v1), per_jd(s, v11)
            have = [j for j in jds if j in a]
            if not have:
                continue
            rows[s] = (a, b, have)
            mean1[s], mean11[s] = (sum(x[j] for j in have) / len(have) for x in (a, b))
        ours_ids = set(m["splits"][split]["ours"])
        lines += [f"## {split.capitalize()} split ({len(jds)} JDs)" + (" (official)" if split == "test" else ""), "",
                  "| System | JDs | nDCG@10 v1 (silver) | nDCG@10 v1.1 (human where graded) [95% CI] | Δ | ours only v1 → v1.1 |",
                  "|---|---|---|---|---|---|"]
        for s, (a, b, have) in sorted(rows.items(), key=lambda kv: -mean11[kv[0]]):
            o = [j for j in have if j in ours_ids]
            o1, o11 = (sum(x[j] for j in o) / len(o) if o else float("nan") for x in (a, b))
            lines.append(f"| {s} | {len(have)} | {mean1[s]:.3f} | "
                         + "{:.3f} [{:.3f}, {:.3f}]".format(*metrics.bootstrap_ci([b[j] for j in have]))
                         + f" | {mean11[s] - mean1[s]:+.3f} | {o1:.3f} → {o11:.3f} |")
        lines += ["", f"Kendall τ between the system orders under v1 and v1.1: **{order_tau(mean1, mean11):.2f}**.", "",
                  "| First | second | Δ v1 | Δ v1.1 | p v1.1 |", "|---|---|---|---|---|"]
        for x, y in HEAD_TO_HEAD:
            if x in rows and y in rows:
                common = [j for j in rows[x][2] if j in rows[y][2]]
                xs, ys = [rows[x][1][j] for j in common], [rows[y][1][j] for j in common]
                d1 = sum(rows[x][0][j] - rows[y][0][j] for j in common) / len(common)
                lines.append(f"| {x} | {y} | {d1:+.3f} | {sum(xs) / len(xs) - sum(ys) / len(ys):+.3f} | "
                             f"{metrics.paired_bootstrap_p(xs, ys):.3f} |")
        lines.append("")
    if conflicts:
        lines += ["Pairs left at silver (the two people ≥ 2 grades apart): " + ", ".join(f"{j}/{c}" for j, c in conflicts), ""]
    DOC.write_text("\n".join(lines), encoding="utf-8")
    return str(DOC)


if __name__ == "__main__":
    print(report())
