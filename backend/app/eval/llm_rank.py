"""E18: does controlled LLM ranking (agent/llm_rank.py) improve the screened order, on labels an LLM did NOT make?

S1 beat P6 on the `ours` silver labels, which Claude annotators made, so its lead may be circularity. The `coding`
benchmark is labelled by a rubric, not by an LLM. A gain on both is evidence; a gain on `ours` only is not.

Per dev JD: the stored B3 ⊕ CE [hybrid] order (rules + cross-encoder, 0 tokens) → its top Settings.llm_rank_size
reordered by the LLM (two passes, opposite orders, positions averaged) → nDCG@10, P@5, traps@10, pass agreement, cost.
Shown next to B3 ⊕ CE, P6 and, on `ours`, S1.

    python -m app.eval.llm_rank [--model claude_code:claude-sonnet-5-5]   → docs/LLM_RANK_RESULTS.md
"""

import argparse
import asyncio
import json

from app import observability
from app.agent import llm_rank
from app.config import ROOT, get_settings
from app.eval import metrics
from app.eval.bench import OUR_TRAPS, load
from app.eval.run import result_path
from app.nlp.injection import neutralize
from app.nlp.pipeline import process
from app.providers import cache
from app.providers.llm import create_llm, default_spec

OUT = ROOT / "docs" / "LLM_RANK_RESULTS.md"
REQ = get_settings().runtime_dir / "eval" / "requirements"
DEV = {b: json.loads((ROOT / "data/eval/benchmark_v1.json").read_text())["splits"]["dev"][b] for b in ("ours", "coding")}


def stored(name: str, bench: str) -> dict:
    p = result_path(name, bench)
    return {k: (v if isinstance(v, list) else v["ranking"]) for k, v in json.loads(p.read_text())["jds"].items()} \
        if p.exists() else {}


def scores(order: list[str], g: dict[str, float], traps: frozenset[str]) -> dict:
    return {"ndcg@10": metrics.ndcg(order, g, 10), "p@5": metrics.precision(order, g, 5),
            "traps@10": sum(c in traps and g.get(c, 0) < 2 for c in order[:10])}


async def run(model_spec: str) -> dict:
    model, k = create_llm(model_spec), get_settings().llm_rank_size
    s1 = json.loads((get_settings().runtime_dir / "eval" / "single_agent.json").read_text())["jds"] \
        if (get_settings().runtime_dir / "eval" / "single_agent.json").exists() else {}
    out = {"model": model_spec, "k": k, "rows": []}
    for bench in ("ours", "coding"):
        b = load(bench)
        traps = b.traps if bench == "ours" else frozenset()
        texts = {d.id: d for d in b.cvs}
        b3, p6 = stored("B3 8-axis ⊕ CE [hybrid]", bench), stored("P6", bench)
        for jd in [j for j in b.jds if j.id in DEV[bench]]:
            g = b.gold[jd.id]
            base = [c for c in b3[jd.id] if c in g] if bench == "coding" else b3[jd.id]  # coding: its JD's labelled pool
            req = json.loads((REQ / bench / "hybrid" / f"{jd.id}.json").read_text())["req"]
            short = base[:k]
            profiles = {c: process(c, texts[c].text, texts[c].meta.get("headline", "")) for c in short}
            usage = observability.UsageCounter()
            res = await llm_rank.rank(model, neutralize(jd.text)[0], req, short, profiles, config={"callbacks": [usage]})
            order = res["order"] + base[k:]
            row = {"bench": bench, "jd": jd.id, "b3": scores(base, g, traps), "llm": scores(order, g, traps),
                   "agreement@5": res["agreement@5"], "tokens": usage.summary()["total_tokens"],
                   "moved_in": [c for c in order[:10] if c not in base[:10]]}
            if jd.id in p6:
                row["p6"] = scores([c for c in p6[jd.id] if c in g] if bench == "coding" else p6[jd.id], g, traps)
            if bench == "ours" and jd.id in s1:
                row["s1"] = {"ndcg@10": s1[jd.id]["s1"]["ndcg@10"]}
            out["rows"].append(row)
            print(f"{bench}/{jd.id}: B3⊕CE {row['b3']['ndcg@10']:.3f} → +LLM rank {row['llm']['ndcg@10']:.3f} "
                  f"(P6 {row.get('p6', {}).get('ndcg@10', float('nan')):.3f}) · agree@5 {res['agreement@5']:.0%} · "
                  f"{row['tokens']:,} tokens")
    return out


def render(r: dict) -> str:
    lines = ["# E18: controlled LLM ranking over the screened shortlist (generated by `python -m app.eval.llm_rank`; "
             "do not edit by hand)", "",
             f"Model `{r['model']}`. The top {r['k']} of B3 ⊕ CE [hybrid] (rules + cross-encoder) are reordered by the LLM "
             "in two passes with opposite input orders, positions averaged (agent/llm_rank.py). Dev JDs only. "
             "`ours` labels were made by Claude annotators; `coding` labels by a rubric, not an LLM.", "",
             "| bench | JD | B3 ⊕ CE | + LLM rank | P6 | S1 | traps@10 B3 → LLM | pass agreement@5 | tokens |",
             "|---|---|---|---|---|---|---|---|---|"]
    for x in r["rows"]:
        f = lambda d: f"{d['ndcg@10']:.3f}" if d else "—"  # noqa: E731
        lines.append(f"| {x['bench']} | {x['jd']} | {x['b3']['ndcg@10']:.3f} | **{x['llm']['ndcg@10']:.3f}** | "
                     f"{f(x.get('p6'))} | {f(x.get('s1'))} | {x['b3']['traps@10']} → {x['llm']['traps@10']} | "
                     f"{x['agreement@5']:.0%} | {x['tokens']:,} |")
    for bench in ("ours", "coding"):
        rows = [x for x in r["rows"] if x["bench"] == bench]
        if rows:
            m = lambda key: sum(x[key]["ndcg@10"] for x in rows if key in x) / max(sum(key in x for x in rows), 1)  # noqa: E731
            lines.append(f"| **{bench} mean** | | **{m('b3'):.3f}** | **{m('llm'):.3f}** | **{m('p6'):.3f}** | "
                         + (f"**{m('s1'):.3f}**" if any("s1" in x for x in rows) else "—") + " | | | |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--model")
    a = ap.parse_args()
    s = get_settings()
    cache.enable(s.runtime_dir / "llm_cache.sqlite")
    res = asyncio.run(run(a.model or default_spec("reasoning")))
    (s.runtime_dir / "eval" / "llm_rank.json").write_text(json.dumps(res, indent=1))
    OUT.write_text(render(res))
    print(render(res))
