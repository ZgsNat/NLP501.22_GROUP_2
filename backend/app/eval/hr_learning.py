"""E24 · HR learning across sessions (lecturer feedback 4), with a simulated HR. Zero LLM calls, no Docker.

Does the ranking for the next JD improve after HR has judged the previous JDs of the same company profile?

Protocol, fixed before the first run (nothing here is tuned: the regression's l2 / lr are calibrate_weights'
defaults, HR sees the top 10, the label thresholds are the benchmark's own "relevant" cut):
  1. Within each benchmark, the JDs of one company profile are HR's sessions, in JD-id order.
  2. Session t ranks the JD's labelled pool by the 8 rule criteria (knock-outs last) with the weights learned in
     sessions 1..t-1, and is scored (nDCG@10) BEFORE its own feedback: a prequential evaluation, so a JD is never
     scored with weights its own labels taught.
  3. HR reads the top 10: approves every CV labelled ≥ 2 ("relevant"), rejects every CV labelled ≤ 0.5; the pairs
     go through calibrate_weights (shrunk towards the current weights) and hr_memory.remember (drift-capped).
  4. "static" ranks the same JD with the company profile's weights. Session 1 is identical by construction, so the
     comparison is over sessions t ≥ 2: mean Δ nDCG@10 and a paired one-sided bootstrap p (learned > static).
Requirements come from the rule JD parser (no LLM). The simulated HR is the label set itself, i.e. a perfectly
consistent HR: the result is an upper bound of what real, noisier HR feedback can teach.

    python -m app.eval.hr_learning            → docs/HR_LEARNING_RESULTS.md
"""

import asyncio
import tempfile
from pathlib import Path

from app.agent import hr_memory
from app.agent.nodes import extract_requirements, profile_weights
from app.agent.scoring import calibrate_weights, knockout_reason, preferences, rule_criteria, rule_total
from app.config import ROOT
from app.eval.bench import load
from app.eval.metrics import ndcg, paired_bootstrap_p
from app.nlp.pipeline import process

OUT = ROOT / "docs" / "HR_LEARNING_RESULTS.md"
SEEN, RELEVANT, IRRELEVANT = 10, 2.0, 0.5


def rank(pool: list[str], prof: dict, req: dict, subs: dict, w: dict[str, float]) -> list[str]:
    ko = {c for c in pool if knockout_reason(prof[c], req["must_have"], subs)}
    return sorted(pool, key=lambda c: (c not in ko, rule_total(prof[c], req, subs, w), c), reverse=True)


def simulated_hr(top: list[str], grades: dict[str, float]) -> list[dict]:
    """HR's decisions on what they saw: approve the relevant, reject the irrelevant, say nothing about the rest."""
    out = []
    for c in top:
        g = grades.get(c, 0.0)
        if g >= RELEVANT:
            out.append({"cv_id": c, "action": "approve", "reason": f"label {g:g}"})
        elif g <= IRRELEVANT:
            out.append({"cv_id": c, "action": "reject", "reason": f"label {g:g}"})
    return out


def sessions(jds: list, profile_of) -> dict[str, list]:
    by: dict[str, list] = {}
    for jd in sorted(jds, key=lambda j: j.id):
        by.setdefault(profile_of(jd), []).append(jd)
    return by


async def run_bench(name: str, memory: Path) -> list[dict]:
    b = load(name)
    profiles = {d.id: process(d.id, d.text, d.meta.get("headline", "")) for d in b.cvs}
    rows = []
    for company, jds in sessions(b.jds, lambda j: j.meta.get("company_profile", "default")).items():
        base = profile_weights(company)
        for t, jd in enumerate(jds, 1):
            req, subs, _ = await extract_requirements(None, jd.text, "rules")
            req = req.model_dump()
            grades = b.gold[jd.id]
            pool = [c for c in grades if c in profiles]
            learned_w, _ = hr_memory.prior(company, base, memory)
            learned = rank(pool, profiles, req, subs, learned_w)
            static = rank(pool, profiles, req, subs, base)
            decisions = simulated_hr(learned[:SEEN], grades)
            pairs = preferences(decisions, learned)
            scores = {c: {k: v["score"] / 100 for k, v in rule_criteria(profiles[c], req, subs).items()} for c in pool}
            new_w = calibrate_weights(pairs, scores, learned_w)
            hr_memory.remember(company, new_w, base, len(pairs), memory)
            rows.append({"bench": name, "company": company, "t": t, "jd": jd.id, "pairs": len(pairs),
                         "static": ndcg(static, grades, 10), "learned": ndcg(learned, grades, 10),
                         "drift": round(sum(abs(learned_w[k] - base[k]) for k in base), 3)})
    return rows


def render(rows: list[dict]) -> str:
    later = [r for r in rows if r["t"] >= 2]
    mean = lambda xs: sum(xs) / len(xs) if xs else float("nan")  # noqa: E731
    lines = ["# E24 · HR learning across sessions (generated by `python -m app.eval.hr_learning`; do not edit by hand)", "",
             "Simulated HR = the benchmark labels (a perfectly consistent HR: an upper bound). Rule ranking, rule JD "
             "parser, zero LLM calls. Each JD is scored before its own feedback (prequential). Protocol: module docstring.",
             "", "| | sessions t ≥ 2 | static nDCG@10 | learned nDCG@10 | Δ | p (learned > static) |", "|---|---|---|---|---|---|"]
    for name in ("all", *sorted({r["bench"] for r in rows})):
        xs = [r for r in later if name == "all" or r["bench"] == name]
        if not xs:
            continue
        s, l = [r["static"] for r in xs], [r["learned"] for r in xs]
        lines.append(f"| {name} | {len(xs)} | {mean(s):.3f} | {mean(l):.3f} | {mean(l) - mean(s):+.3f} | "
                     f"{paired_bootstrap_p(l, s):.3f} |")
    lines += ["", "| bench | company profile | session | JD | static | learned | drift from profile (Σ|Δw|) | "
              "pairs HR gave |", "|---|---|---|---|---|---|---|---|"]
    lines += [f"| {r['bench']} | {r['company']} | {r['t']} | {r['jd']} | {r['static']:.3f} | {r['learned']:.3f} | "
              f"{r['drift']:.3f} | {r['pairs']} |" for r in rows]
    return "\n".join(lines) + "\n"


async def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        # one memory per benchmark (never the real .runtime/hr_memory.json): "bank" in both must not share labels
        rows = [r for name in ("ours", "coding") for r in await run_bench(name, Path(tmp) / f"{name}.json")]
    OUT.write_text(render(rows), encoding="utf-8")
    print(OUT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    asyncio.run(main())
