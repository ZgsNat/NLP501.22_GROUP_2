"""E20 · Contrastive learning (lecturer feedback 2): does a ConFit-style fine-tuned encoder help OUR ranking?

The training itself is the coding branch's (cv_agent/training/finetune.py, Đán): multilingual-e5-base fine-tuned with
(Cached)MultipleNegativesRankingLoss on (JD, Good-Fit resume, No-Fit resume) triplets of the public
`cnamuangtoun/resume-job-description-fit` dataset, in-batch negatives, QA JDs and their resumes held out, 3 seeds;
run on a GPU (`notebooks/finetune_colab.ipynb` or `python -m cv_agent finetune --seeds 42,7,13`). This module only
evaluates the result, base vs fine-tuned, inside our ladder and on our benchmarks, so the question is answered with
the same labels and metrics as every other rung:

    B1 e5          the base encoder, whole CV (the B1 rung with a multilingual encoder)
    B1 e5-ft       the fine-tuned encoder, same input                         → effect of contrastive training alone
    B3 ⊕ e5[-ft]   8 rule criteria (rule JD parser) fused with that encoder like `B3 8-axis ⊕ CE`
                                                                               → does it still help the full ranker?

Zero LLM calls (rule JD parser), no Qdrant. Results are saved like any rung (`run report --bench …` lists them) and
summarised in docs/CONTRASTIVE_RESULTS.md. Per docs/BENCHMARK.md: compare on dev, report test once.

    uv run --with sentence-transformers python -m app.eval.contrastive \\
        --base intfloat/multilingual-e5-base --ft <dir of the fine-tuned model> [--bench ours,coding]
"""

import argparse
import asyncio
from pathlib import Path

from app.agent.nodes import extract_requirements, profile_weights
from app.agent.scoring import knockout_reason, rule_total
from app.config import ROOT
from app.eval.bench import load
from app.eval.metrics import ndcg
from app.eval.run import full_order, save
from app.nlp.pipeline import process

OUT = ROOT / "docs" / "CONTRASTIVE_RESULTS.md"


def is_e5(model_name: str) -> bool:
    """multilingual-e5 expects 'query: ' / 'passage: ' (judged by the model's own folder name, as in finetune.py)."""
    return "e5" in Path(model_name).name


def prefixed(texts: list[str], kind: str, model_name: str) -> list[str]:
    return [f"{kind}: {t}" for t in texts] if is_e5(model_name) else list(texts)


def fused(pool: list[str], dense: dict[str, float], rule: dict[str, float], ko: set[str]) -> list[str]:
    """`B3 8-axis ⊕ CE` with the encoder in the CE's place: eligible CVs by the mean of min-max normalised dense and
    rule scores, then knocked-out CVs by rule score."""
    ok = [c for c in pool if c not in ko]

    def norm(xs: dict[str, float]) -> dict[str, float]:
        lo, hi = min(xs.values()), max(xs.values())
        return {k: (v - lo) / ((hi - lo) or 1) for k, v in xs.items()}

    d, r = (norm({c: dense[c] for c in ok}), norm({c: rule[c] for c in ok})) if ok else ({}, {})
    head = sorted(ok, key=lambda c: (d[c] + r[c], c), reverse=True)
    return head + sorted((c for c in pool if c in ko), key=lambda c: (rule[c], c), reverse=True)


def systems(model, name: str, bench: str, label: str) -> dict[str, dict[str, list[str]]]:
    b = load(bench)
    pool = [d.id for d in b.cvs]
    texts = {d.id: d.text for d in b.cvs}
    prof = {d.id: process(d.id, d.text, d.meta.get("headline", "")) for d in b.cvs}
    docs = model.encode(prefixed([texts[c] for c in pool], "passage", name), normalize_embeddings=True, batch_size=16)
    out: dict[str, dict[str, list[str]]] = {f"B1 {label}": {}, f"B3 8-axis ⊕ {label} [rules]": {}}
    for jd in b.jds:
        q = model.encode(prefixed([jd.text], "query", name), normalize_embeddings=True)[0]
        dense = dict(zip(pool, (docs @ q).tolist()))
        req, subs, _ = asyncio.run(extract_requirements(None, jd.text, "rules"))
        req = req.model_dump()
        w = profile_weights(jd.meta.get("company_profile", "default"))
        ko = {c for c in pool if knockout_reason(prof[c], req["must_have"], subs)}
        rule = {c: rule_total(prof[c], req, subs, w) for c in pool}
        out[f"B1 {label}"][jd.id] = full_order(sorted(pool, key=lambda c: (dense[c], c), reverse=True), pool)
        out[f"B3 8-axis ⊕ {label} [rules]"][jd.id] = fused(pool, dense, rule, ko)
    return out


def render(rows: list[tuple[str, str, str, float, int]]) -> str:
    lines = ["# E20 · Contrastive fine-tuning in our ladder (generated by `python -m app.eval.contrastive`; do not edit "
             "by hand)", "", "Encoder fine-tuned by the coding branch's ConFit-style recipe (MNRL, in-batch negatives, "
             "public resume–job-fit data, QA JDs held out). Evaluated here on our benchmarks, zero LLM calls. Protocol: "
             "module docstring. Compare on dev; test is reported once.", "",
             "| bench | split | system | nDCG@10 | JDs |", "|---|---|---|---|---|"]
    lines += [f"| {b} | {sp} | {s} | {v:.3f} | {n} |" for b, sp, s, v, n in rows]
    return "\n".join(lines) + "\n"


def split_of(bench: str) -> dict[str, str]:
    import json

    m = json.loads((ROOT / "data" / "eval" / "benchmark_v1.json").read_text())["splits"]
    return {j: sp for sp in ("dev", "test") for j in m[sp].get(bench, [])}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="intfloat/multilingual-e5-base")
    ap.add_argument("--ft", required=True, help="folder of the fine-tuned model (coding branch: models/…-rjf-ft)")
    ap.add_argument("--bench", default="ours,coding")
    a = ap.parse_args()
    from sentence_transformers import SentenceTransformer

    rows = []
    for name, label in ((a.base, "e5"), (a.ft, "e5-ft")):
        model = SentenceTransformer(name)
        for bench in a.bench.split(","):
            g, sp = load(bench).gold, split_of(bench)
            for system, per_jd in systems(model, name, bench, label).items():
                save(system, per_jd, bench)
                for split in ("dev", "test"):
                    jds = [j for j in per_jd if sp.get(j, "test") == split and j in g]
                    if jds:
                        v = sum(ndcg([c for c in per_jd[j] if c in g[j]], g[j], 10) for j in jds) / len(jds)
                        rows.append((bench, split, system, v, len(jds)))
    OUT.write_text(render(sorted(rows)))
    print(OUT.read_text())


if __name__ == "__main__":
    main()
