"""E21: does selectivity save tokens? The deck's H2 (−78% tokens) measured as it was meant (docs/FINAL_REPORT.md §H2).

    cd backend && uv run python -m app.eval.run agent --systems B4,P6,E-every --jds <dev JDs>   (per bench)
    cd backend && uv run python -m app.eval.token_cost                    → docs/TOKEN_COST_RESULTS.md

Same JDs, same model, same graph. E-every switches the selectivity off (run.SYSTEM_SETTINGS): the LLM assesses every
retrieved CV that passes the knock-out and arbitrates every adjacent top-5 pair. P6 assesses a shortlist of 8 and
arbitrates near-ties only; B4 is P6 with every loop off. Saving = 1 − tokens(system) / tokens(E-every), paired by JD.
"""

import json

from app.config import ROOT
from app.eval import metrics
from app.eval.bench import load
from app.eval.benchmark import MANIFEST
from app.eval.run import result_path, score_system

DOC = ROOT / "docs" / "TOKEN_COST_RESULTS.md"
SYSTEMS = ("B4", "P6", "E-every")
REFERENCE = "E-every"


def per_jd(system: str, split: str = "dev") -> dict[str, dict]:
    """JD → {tokens, calls, seconds, ndcg@10} for the split's JDs the system has results for."""
    m, out = json.loads(MANIFEST.read_text()), {}
    for src, jds in m["splits"][split].items():
        path = result_path(system, src)
        if not path.exists():
            continue
        runs = {j: r for j, r in json.loads(path.read_text())["jds"].items() if j in jds}
        if not runs:
            continue
        b = load(src)
        sc = score_system(runs, b.gold, b.traps)
        for j, nd in zip(sc["jds"], sc["ndcg@10"]):
            out[j] = {"tokens": runs[j]["tokens"], "calls": runs[j]["calls"], "seconds": runs[j]["seconds"], "ndcg@10": nd}
    return out


def saving(system: dict[str, dict], reference: dict[str, dict]) -> tuple[float, list[str]]:
    """1 − Σ tokens(system) / Σ tokens(reference) over the JDs both have (a pooled ratio, not a mean of ratios)."""
    common = sorted(set(system) & set(reference))
    ref = sum(reference[j]["tokens"] for j in common)
    return (1 - sum(system[j]["tokens"] for j in common) / ref if ref else float("nan")), common


def report() -> str:
    runs = {s: per_jd(s) for s in SYSTEMS}
    common = sorted(set.intersection(*(set(r) for r in runs.values()))) if all(runs.values()) else []
    lines = ["# Token cost of selectivity (generated by `python -m app.eval.token_cost`; do not edit by hand)", "",
             "Dev JDs of NLP501-bench v1, the same graph and model (Claude Sonnet 5.5 / Haiku 5.5 via claude_code, "
             "tokens as the CLI reports them). E-every = P6 with the LLM on every eligible candidate and every top-5 "
             "pair. Mean per JD over the JDs all three systems finished; nDCG@10 with a 95% bootstrap CI.", "",
             f"JDs in common: {len(common)} ({', '.join(common) or 'none yet'})", "",
             "| System | tokens / JD | LLM calls / JD | seconds / JD | nDCG@10 [95% CI] | tokens saved vs E-every |",
             "|---|---|---|---|---|---|"]
    for s in SYSTEMS:
        r = {j: runs[s][j] for j in common}
        if not r:
            lines.append(f"| {s} | not run | | | | |")
            continue
        mean = lambda k: sum(x[k] for x in r.values()) / len(r)  # noqa: E731
        ci = "{:.3f} [{:.3f}, {:.3f}]".format(*metrics.bootstrap_ci([x["ndcg@10"] for x in r.values()]))
        save = "—" if s == REFERENCE else f"{saving(r, {j: runs[REFERENCE][j] for j in common})[0]:.1%}"
        lines.append(f"| {s} | {mean('tokens'):,.0f} | {mean('calls'):.1f} | {mean('seconds'):.0f} | {ci} | {save} |")
    if common:
        lines += ["", "| First | second | ΔnDCG@10 | p (first > second) |", "|---|---|---|---|"]
        for a, b in (("P6", "E-every"), ("E-every", "P6"), ("B4", "E-every")):
            xs, ys = [runs[a][j]["ndcg@10"] for j in common], [runs[b][j]["ndcg@10"] for j in common]
            lines.append(f"| {a} | {b} | {sum(xs) / len(xs) - sum(ys) / len(ys):+.3f} | "
                         f"{metrics.paired_bootstrap_p(xs, ys):.3f} |")
        lines += ["", "Per JD tokens:", "", "| JD | " + " | ".join(SYSTEMS) + " |", "|---|" + "---|" * len(SYSTEMS)]
        lines += [f"| {j} | " + " | ".join(f"{runs[s][j]['tokens']:,}" for s in SYSTEMS) + " |" for j in common]
    lines += ["", "Deck target (H2): −78% tokens. Compare the P6 row's saving with it."]
    DOC.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return str(DOC)


if __name__ == "__main__":
    print(report())
